"""Generate results/RESULTS.md and results/verdicts.json from the raw metric JSONs. Usage: python scripts/make_results.py"""
import json, math, sys
sys.stdout.reconfigure(encoding="utf-8")
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
import numpy as np
from emoprobe.paths import RESULTS

NAMES = {"llama8b": "Llama-3.1-8B-Instruct (main)", "qwen3b": "Qwen2.5-3B-Instruct (replication)"}
CS = [-8, -4, -2, 0, 2, 4, 8]
VECS = ["d1", "d2", "d1_deconf", "random"]


def f(x, d=2):
    return "–" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{d}f}"


def ci(t, d=2):
    return f"{f(t[0], d)} [{f(t[1], d)}, {f(t[2], d)}]" if t and t[0] is not None else "–"


def probe_verdicts(pm):
    Ls, L, j = pm["layers"], pm["n_blocks"], pm["steer_layer"]
    rng = range(math.ceil(L / 3), L + 1)
    ok = [jj for jj in rng if pm["layers"][jj]["md:d1_test"]["acc"][1] > 0.8 and pm["layers"][jj]["lr:d1_test"]["acc"][1] > 0.8]
    h1 = dict(layers_checked=[rng.start, rng.stop - 1], n_layers_passing=len(ok), n_layers=len(rng),
              supported=len(ok) >= len(rng) / 2)
    au = Ls[j]["md:d2_test"]["auroc"]
    strength = "strong" if au[0] >= 0.8 else "moderate" if au[0] >= 0.65 else "weak"
    h2 = dict(layer=j, auroc=au, supported=au[1] > 0.5, strength=strength)
    h2s = dict(p_vs_random=Ls[j]["transfer_p_random"], p_vs_shuffled=Ls[j]["transfer_p_shuffle"],
               irrelevant_frac_as_strong=Ls[j]["irrelevant_dirs_frac_as_strong"],
               supported=Ls[j]["transfer_p_random"] < 0.05)
    return h1, h2, h2s


def overall(h2, h2s, sm):
    h2_ok = h2["supported"] and h2["strength"] in ("moderate", "strong") and h2s["supported"]
    if not sm or "H3" not in sm:
        return "pending (steering not judged yet)"
    h3 = sm["H3"]["supported"]
    d2_better = sm["contrasts_emotion"]["d2-d1@+4"][1] > 0
    if h2_ok and h3:
        return "emotion direction"
    if (not h2_ok) and ((not h3) or d2_better):
        return "mostly instruction detector"
    return "mixed"


lines = ["# RESULTS", "", "_Generated by `scripts/make_results.py` from the JSON files in `results/`. Do not edit by hand._", "",
         "Pre-registered tests: H1, H2, H2-specific (amendment 4), H3, H4. **Everything else is exploratory.**", ""]
verdicts = {}
for S in ("llama8b", "qwen3b"):
    pmf = RESULTS / S / "probe_metrics.json"
    if not pmf.exists():
        continue
    pm = json.loads(pmf.read_text())
    smf = RESULTS / S / "steering_metrics.json"
    sm = json.loads(smf.read_text()) if smf.exists() else None
    if sm and not sm.get("n_judged"):
        sm_j = None
    else:
        sm_j = sm
    Ls, j = pm["layers"], pm["steer_layer"]
    h1, h2, h2s = probe_verdicts(pm)
    v = dict(H1=h1, H2=h2, H2_specific=h2s, steer_layer=j)
    if sm_j:
        v["H3"], v["H4"] = sm_j["H3"], sm_j["H4"]
    v["overall"] = overall(h2, h2s, sm_j)
    verdicts[S] = v
    R = Ls[j]
    lines += [f"## {NAMES[S]}", "",
              f"{pm['n_blocks']} blocks, d_model = {pm['d_model']}. Residual index j = 0 is the embeddings, j = i+1 is the output of block i.", "",
              "### Pre-registered verdicts", "",
              f"- **H1** (D1 decodable mid-to-late): {'SUPPORTED' if h1['supported'] else 'NOT supported'} — "
              f"{h1['n_layers_passing']}/{h1['n_layers']} layers in j∈[{h1['layers_checked'][0]},{h1['layers_checked'][1]}] have both direction and probe held-out accuracy with CI lower bound > 0.80.",
              f"- **H2** (D1→D2 transfer above chance, j* = {j}): {'SUPPORTED' if h2['supported'] else 'NOT supported'} — AUROC {ci(h2['auroc'])} ({h2['strength']}).",
              f"- **H2-specific** (beats random directions): {'SUPPORTED' if h2s['supported'] else 'NOT supported'} — one-sided p = {f(h2s['p_vs_random'], 3)} vs 1000 random directions; "
              f"p = {f(h2s['p_vs_shuffled'], 3)} vs 1000 label-shuffled D1 directions (exploratory); {f(100 * h2s['irrelevant_frac_as_strong'], 0)}% of 24 irrelevant-contrast directions separate D2 at least as strongly (sign ignored)."]
    if sm_j:
        h3, h4 = sm_j["H3"], sm_j["H4"]
        lines += [f"- **H3** (D1 steering > random at c=+4, task completion ≥ 0.70): {'SUPPORTED' if h3['supported'] else 'NOT supported'} — "
                  f"emotion difference D1 − random = {ci(h3['diff_d1_minus_random'])}; D1 task completion = {f(h3['task_completion_d1'])}.",
                  f"- **H4** (D2 steers at least as well as D1): {'SUPPORTED' if h4['supported'] else 'NOT supported'} — "
                  f"D2 − D1 = {ci(h4['diff_d2_minus_d1'])} (needs lower bound > −1); D2 − random = {ci(h4['diff_d2_minus_random'])}."]
    else:
        lines += ["- **H3/H4**: pending (generations not yet judged)."]
    lines += [f"- **Overall (pre-registered rule):** {v['overall']}", ""]

    # per-layer table
    lines += ["### Stage 1: per-layer reading results (exploratory detail)", "",
              "AUROC/accuracy with 95% cluster-bootstrap CIs. 'md' = mean-difference direction, 'lr' = logistic probe.", "",
              "| j | D1 acc (md) | D1 acc (lr) | D1→D2 AUROC (md) | random-dir 95% band | p vs random | D1→D3 instr. (mean) | D1→D3 content (mean) | control acc (lr) | selectivity | para-ID acc | negation acc (md) | cos(D1,D2) |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    show = sorted(set(list(range(0, len(Ls), 4)) + [j, len(Ls) - 1]))
    for jj in show:
        L_ = Ls[jj]
        d3i = np.mean([L_[f"md:d3_d1_{x}"]["auroc"][0] for x in ("mcq", "json", "plain")])
        d3c = np.mean([L_[f"md:d3_d2_{x}"]["auroc"][0] for x in ("mcq", "json", "plain")])
        sel = L_["lr:d1_test"]["acc"][0] - L_["lr:ctrl_d1_test"]["acc"][0]
        band = L_.get("transfer_null_random95", [None, None])
        lines.append(f"| {jj}{' *' if jj == j else ''} | {ci(L_['md:d1_test']['acc'])} | {ci(L_['lr:d1_test']['acc'])} | {ci(L_['md:d2_test']['auroc'])} | "
                     f"[{f(band[0])}, {f(band[1])}] | {f(L_.get('transfer_p_random'), 3)} | {f(d3i)} | {f(d3c)} | {ci(L_['lr:ctrl_d1_test']['acc'])} | {f(sel)} | "
                     f"{f(L_['para_id_acc'][0])} | {f(L_['md:d1neg']['acc'][0])} | {f(L_['cos_d1_d2'])} |")
    lines += ["", "\\* = steering layer j*.", ""]

    # confounds at j*
    lx = pm["lexical_baseline"]
    lines += [f"### Confounds and controls at j* = {j} (exploratory)", "",
              f"- **Text-only baseline** (TF-IDF logistic on the raw prompt, trained on D1): D1 test accuracy {ci(lx['d1_test']['acc'])}; "
              f"→ D2 AUROC {ci(lx['d2_test']['auroc'])}; → negation set accuracy {ci(lx['d1neg']['acc'])}. "
              f"So D1 accuracy on its own carries no information: the words alone give it.",
              f"- **Paraphrase identity** (10-way probe, chance 0.10): {ci(R['para_id_acc'])}. The activations record *which* instruction string was used.",
              f"- **Leave-paraphrase-out** (train on paraphrase slots 0–2, test on 3–4): direction accuracy {ci(R['md:lpo_d1_test']['acc'])}.",
              f"- **Control task** (Hewitt & Liang; random label per (paraphrase, task verb) type; label agreement with truth {f(pm['control_label_agreement_with_true'])}): "
              f"probe test accuracy {ci(R['lr:ctrl_d1_test']['acc'])}, train {f(R['lr:ctrl_train_acc'])}; selectivity = {f(R['lr:d1_test']['acc'][0] - R['lr:ctrl_d1_test']['acc'][0])}.",
              f"- **Negation test** ('Do not be warm…' = cold, 'Do not be cold…' = warm): D1 direction accuracy {ci(R['md:d1neg']['acc'])}, AUROC {ci(R['md:d1neg']['auroc'])}. "
              f"D2 direction on the same set: AUROC {ci(R['md2:d1neg']['auroc'])}.",
              f"- **Length**: token count alone on D2 test, AUROC {ci(pm['length_baseline_auroc']['d2_test']['auroc'])}; D1→D2 transfer after regressing out token count: {ci(R['md:d2_test_len_resid']['auroc'])}.",
              f"- **Logistic probe** D1→D2 AUROC: {ci(R['lr:d2_test']['auroc'])}. D2-trained direction → D2 test: {ci(R['md2:d2_test']['auroc'])}; D2 direction → D1 test: {ci(R['md2:d1_test']['auroc'])}.",
              f"- **D3 formats** (D1 direction AUROC): instruction contrast MCQ {ci(R['md:d3_d1_mcq']['auroc'])}, JSON {ci(R['md:d3_d1_json']['auroc'])}, plain {ci(R['md:d3_d1_plain']['auroc'])}; "
              f"content contrast MCQ {ci(R['md:d3_d2_mcq']['auroc'])}, JSON {ci(R['md:d3_d2_json']['auroc'])}, plain {ci(R['md:d3_d2_plain']['auroc'])}.",
              f"- **Cosine** D1 vs D2 direction: {f(R['cos_d1_d2'])} (95% |cos| under shuffled D1 labels: {f(R['cos_null_abs95'])}).",
              "- **Irrelevant-contrast directions** most separating D2 (AUROC): " +
              ", ".join(f"{k} {f(x)}" for k, x in sorted(R["irrelevant_dirs_d2_auroc"].items(), key=lambda t: -abs(t[1] - 0.5))[:5]) + ".",
              "- **Per emotion** (D1 direction, D2 test pairs of that emotion): " +
              ", ".join(f"{e} {ci(x['auroc'])} (n={x['n_pairs']})" for e, x in pm["per_emotion_at_steer_layer"].items()) + ".", ""]
    lines += [f"### Deconfounding (exploratory, j* = {j})", "",
              f"Format/paraphrase/instruction-presence subspace rank {R['subspace_rank']}; share of the D1 direction's squared norm inside it: {f(R['d1_frac_in_subspace'])}.", "",
              "| components removed k | D1→D2 AUROC | D1 test AUROC |", "|---|---|---|"]
    for k in pm["k_list"]:
        lines.append(f"| {k} | {ci(R[f'deconf_k{k}:d2_test']['auroc'])} | {ci(R[f'deconf_k{k}:d1_test']['auroc'])} |")
    lines.append(f"| full span (used for steering) | {ci(R['mdx:d2_test']['auroc'])} | {ci(R['mdx:d1_test']['auroc'])} |")
    lines.append("")

    if sm:
        lines += [f"### Stage 2: steering (layer {sm['layer']}, α = c × {f(sm['alpha_per_c'], 3)}, {sm['n_prompts']} prompts, "
                  f"{sm['n_generations']} generations, {sm['n_judged']} judged)", ""]
        cal = RESULTS / S / "calibration.json"
        if cal.exists():
            c_ = json.loads(cal.read_text())
            lines += [f"Calibration: typical residual norm {f(c_['typical_norm'], 1)}; breaking point f* = {c_['f_star']} "
                      f"(unsteered calibration perplexity {f(c_['base_ppl'])}); so c = ±8 ↔ {c_['f_star']} × typical norm.", ""]
        for key, title, d in (("emotion", "Judge emotional intensity (1–10)", 2), ("task_completed", "Judge task completion rate", 2),
                              ("ppl_geomean", "Perplexity under unsteered model (geometric mean)", 2),
                              ("judge_refusal", "Judge refusal rate", 2), ("rx_refusal", "Regex refusal rate", 2),
                              ("rx_apology", "Regex apology-word rate", 2), ("rx_bullets", "Regex bullet/numbered-list rate", 2)):
            if key in ("emotion", "task_completed", "judge_refusal") and not sm["n_judged"]:
                continue
            lines += [f"**{title}** (mean [95% CI over prompts])", "", "| vector | " + " | ".join(f"c={c:+d}" for c in CS) + " |",
                      "|---|" + "---|" * len(CS)]
            for vv in VECS:
                lines.append(f"| {vv} | " + " | ".join(ci(sm["dose"][key][vv][str(c)], d) for c in CS) + " |")
            lines.append("")
        if sm["n_judged"]:
            lines += ["**Paired emotion contrasts** (difference in judge score, 95% CI over prompts)", "",
                      "| contrast | " + " | ".join(f"c={c:+d}" for c in CS if c) + " |", "|---|" + "---|" * 6]
            for name in ("d1-random", "d2-random", "d1_deconf-random", "d2-d1", "d1_deconf-d1"):
                lines.append(f"| {name} | " + " | ".join(ci(sm["contrasts_emotion"][f"{name}@{c:+d}"]) for c in CS if c) + " |")
            lines.append("")

agr = RESULTS / "judge_human_agreement.json"
lines += ["## Judge validation", ""]
if agr.exists():
    a = json.loads(agr.read_text())
    lines += [f"Hand labels by Murt on {a['n']} outputs: Spearman ρ = {f(a['spearman'])}, mean |judge − human| = {f(a['mean_abs_diff'])} points, "
              f"mean (judge − human) = {f(a['judge_minus_human_mean'])}. Task completion: agreement {f(a.get('task_agreement'))}, Cohen's κ = {f(a.get('task_kappa'))} (n={a.get('task_n')}).", ""]
else:
    lines += ["Pending: `results/human_labels.csv` not yet filled in.", ""]
costs = RESULTS / "costs.json"
if costs.exists():
    cc = json.loads(costs.read_text())
    lines += ["## Compute spend", "", "Modal (own estimate from wall-clock × A10G list price): " +
              "; ".join(f"{c['stage']} {f(c['seconds'], 0)} s ≈ ${f(c['est_usd'], 3)}" for c in cc) +
              f". Total ≈ ${f(sum(c['est_usd'] for c in cc), 2)}.", ""]
jc = RESULTS / "judge_costs.json"
if jc.exists():
    c = json.loads(jc.read_text())
    lines += [f"Fireworks judge: {c['prompt_tokens']:,} prompt + {c['completion_tokens']:,} completion tokens "
              f"≈ ${c['prompt_tokens'] / 1e6 * 0.15 + c['completion_tokens'] / 1e6 * 0.60:.2f} at the assumed list price.", ""]
(RESULTS / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
(RESULTS / "verdicts.json").write_text(json.dumps(verdicts, indent=1))
print("\n".join(lines[:40]))
